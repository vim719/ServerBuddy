import 'dart:convert';
import 'dart:io';

import 'package:serverbuddy_server/src/agent/agora_token.dart';
import 'package:test/test.dart';

void main() {
  const appId = '0123456789abcdef0123456789abcdef';
  const cert = 'fedcba9876543210fedcba9876543210';
  const pythonSdkPayload =
      'IAAgqZCawyME16AijoGEFsT77X7MldPYsKt9bVBJlDD3CSAAMDEyMzQ1Njc4OWFiY2RlZjAxMjM0NTY3ODlhYmNkZWYA8VNlEA4AAJIQAAACAAEABAABABAOAAACABAOAAADABAOAAAEABAOAAAKAG1lbW9yeS0xLTIIADEyMzQ1Njc4AgABAAEAEA4AAAgAMTIzNDU2Nzg=';

  String payload(String token) =>
      base64.encode(ZLibCodec().decode(base64.decode(token.substring(3))));

  test('matches the Agora Python SDK token for the same inputs', () {
    final token = AgoraToken.convoAiToken(
      appId: appId,
      appCertificate: cert,
      channelName: 'memory-1-2',
      uid: 12345678,
      tokenExpire: 3600,
      issueTs: 1700000000,
      salt: 4242,
    );
    expect(token, startsWith('007'));
    // Generated by agora_agent.agentkit.token.generate_convo_ai_token (Python SDK).
    expect(payload(token), pythonSdkPayload);
  });

  test('rejects malformed credentials', () {
    expect(
      () => AgoraToken.convoAiToken(
        appId: 'short',
        appCertificate: cert,
        channelName: 'c',
        uid: 1,
      ),
      throwsArgumentError,
    );
  });
}
